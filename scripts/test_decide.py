def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def replace_once(text: str, old: str, new: str) -> str:
    """Replace the one occurrence of ``old``; a fixture edit that matches nothing must fail loudly."""
    if text.count(old) != 1:
        raise AssertionError(f"fixture edit expects exactly one {old!r}, found {text.count(old)}")
    return text.replace(old, new)


def generate_core(target: Path) -> None:
    completed = subprocess.run(
        [sys.executable, str(INIT), "new", "--name", "Decide Demo", "--target", str(target), "--no-init-git",
         "--profile", "core"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    if completed.returncode != 0:
        raise AssertionError(completed.stdout + completed.stderr)


def record_passing_journey(target: Path) -> None:
    """Write synthetic records for gate tests: a passed journey and the evidence summary that matches it."""
    path = target / "PROJECT.md"
    text = replace_once(path.read_text(encoding="utf-8"),
                        f"Not yet defined {EM_DASH} the human must confirm the primary user.",
                        "A student using the local application.")
    text = replace_once(text, f"Not yet defined {EM_DASH} the human must state the observable product outcome.",
                        "A student completes one saved workflow through the documented launcher.")
    path.write_text(text, encoding="utf-8")

    path = target / "STATE.yaml"
    state = path.read_text(encoding="utf-8")
    for old, new in (
        ("status: planned", "status: validated"),
        (f'description: "Not yet defined {EM_DASH} derive the smallest end-to-end user journey from PROJECT.md."',
         'description: "Run the documented local workflow end to end."'),
        (f'command: "Not yet defined {EM_DASH} record the exact human-authorized command."',
         'command: "python3 -m unittest"'),
        (f'environment: "Not yet defined {EM_DASH} record the representative environment."',
         'environment: "clean local test fixture"'),
        ("    status: not_run", "    status: passed"),
        ("primary_journey: not_run", "primary_journey: passed"),
        ("automated_tests: not_run", "automated_tests: passed"),
        ('blockers:\n  - "Primary user and product outcome require human confirmation."', "blockers: []"),
    ):
        state = replace_once(state, old, new)
    path.write_text(state, encoding="utf-8")

    path = target / SUMMARY
    summary = path.read_text(encoding="utf-8")
    for old, new in (
        ("Environment: not recorded", "Environment: clean local test fixture"),
        ("Command: not recorded", "Command: `python3 -m unittest`"),
        ("Result: not run", "Result: passed"),
        ("Exit code: not recorded", "Exit code: 0"),
    ):
        summary = replace_once(summary, old, new)
    path.write_text(summary, encoding="utf-8")


def setUpModule() -> None:
    global _TMP, BASE
    _TMP = tempfile.TemporaryDirectory()
    BASE = Path(_TMP.name).resolve() / "base"
    generate_core(BASE)
    record_passing_journey(BASE)
