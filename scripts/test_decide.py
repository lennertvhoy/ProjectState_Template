class LoopTests(DecideCase):
    """The doctor lists a decision, the inbox command records it, and the doctor stops listing it."""

    def listed(self, fleet_root: Path) -> dict[str, str]:
        code, out, err = run_main(fleet, "--root", str(fleet_root), "--stdout", "--format", "json")
        self.assertEqual(code, 0, err)
        report = json.loads(out)
        self.assertEqual(report["summary"]["inbox"]["decisions"], len(report["inbox"]["decisions"]))
        return {item["repository"]: item["command"] for item in report["inbox"]["decisions"]}

    def test_the_inbox_command_records_each_decision_and_the_doctor_stops_listing_it(self) -> None:
        fleet_root = self.tmp / "fleet"
        fleet_root.mkdir()
        for name in ("alpha", "beta", "gamma"):
            shutil.copytree(BASE, fleet_root / name)
        commands = self.listed(fleet_root)
        self.assertEqual(sorted(commands), ["alpha", "beta", "gamma"])
        for name, decision in (("alpha", "accept"), ("beta", "waive"), ("gamma", "reject")):
            parts = shlex.split(commands[name])
            self.assertEqual((parts[0], Path(parts[1]), parts[2:4]),
                             ("python3", DECIDE, [str(fleet_root / name), "accept|reject|waive"]))
            parts[0], parts[3], parts[4] = sys.executable, decision, "Recorded from the inbox command."
            completed = subprocess.run(parts, capture_output=True, text=True, check=False, cwd=self.tmp)
            self.assertEqual((completed.returncode, completed.stderr), (0, ""), completed.stdout)
            errors, _, _ = gate.validate(fleet_root / name)
            self.assertEqual(errors, [])
            self.assertNotIn(name, self.listed(fleet_root))
        self.assertEqual(self.listed(fleet_root), {})

    def test_command_line_entry_point_and_exit_codes(self) -> None:
        run = [sys.executable, str(DECIDE)]
        done = subprocess.run([*run, str(self.root), "accept", "Fine."], capture_output=True, text=True, check=False)
        self.assertEqual((done.returncode, done.stderr), (0, ""), done.stdout)
        self.assertIn("recorded: accepted for slice bootstrap-001", done.stdout)
        again = subprocess.run([*run, str(self.root), "accept", "Fine."], capture_output=True, text=True, check=False)
        self.assertEqual((again.returncode, again.stdout), (2, ""))
        self.assertIn("refused: validation.human_acceptance is 'accepted', not pending", again.stderr)
        invalid = subprocess.run([*run, str(self.root), "approve", "Fine."], capture_output=True, text=True,
                                 check=False)
        self.assertEqual(invalid.returncode, 2)
        self.assertIn("invalid choice", invalid.stderr)
        helped = subprocess.run([*run, "--help"], capture_output=True, text=True, check=False)
        self.assertEqual(helped.returncode, 0)
        for option in ("--date", "--slice", "--dry-run", "--allow-dirty", "OWNER_WORDS"):
            self.assertIn(option, helped.stdout)
        self.assertEqual(list(self.root.rglob("__pycache__")), [])


