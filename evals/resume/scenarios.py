def get_scenario(key: str) -> Scenario:
    """Look a scenario up by letter (``a``) or slug (``failed-journey``)."""
    for scenario in SCENARIOS:
        if key in (scenario.letter, scenario.slug, scenario.label):
            return scenario
    raise ScenarioError(f"unknown scenario {key!r}; expected one of {[s.label for s in SCENARIOS]}")


# --- trusted runs ----------------------------------------------------------------------------------------------


def clean_env() -> dict[str, str]:
    """An environment for trusted runs: no notes variables (so no sync token) and no bytecode written into repos."""
    env = {key: value for key, value in os.environ.items() if key not in SCRUBBED_ENV}
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def journey_status(exit_code: int) -> str:
    return {0: "passed", BLOCKED_EXIT: "blocked"}.get(exit_code, "failed")


def observe_journey(journey_text: str, root: Path, *, timeout: int = 60) -> Observation:
    """Run a trusted copy of the journey against the product in ``root`` and report what really happens."""
    with tempfile.TemporaryDirectory(prefix="psresume-journey-") as tmp:
        script = Path(tmp) / "journey.py"
        script.write_text(journey_text, encoding="utf-8")
        try:
            completed = subprocess.run(
                [sys.executable, str(script), "--root", str(root)],
                cwd=root,
                env=clean_env(),
                capture_output=True,
                text=True,
                timeout=timeout,
                check=False,
            )
        except subprocess.TimeoutExpired:
            return Observation("failed", -1, f"journey timed out after {timeout}s")
    return Observation(
        journey_status(completed.returncode),
        completed.returncode,
        (completed.stdout + completed.stderr).strip(),
    )


def run_unit_tests(root: Path, *, timeout: int = 60) -> bool:
    try:
        completed = subprocess.run(
            [sys.executable, "-m", "unittest", "-q"],
            cwd=root,
            env=clean_env(),
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return False
    return completed.returncode == 0


def run_gate(repo: Path, gate_script: Path | None = None) -> tuple[int, str]:
    script = gate_script or repo / "scripts" / "projectstate_gate.py"
    completed = subprocess.run(
        [sys.executable, str(script), "--root", str(repo)],
        cwd=repo,
        env=clean_env(),
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    return completed.returncode, (completed.stdout + completed.stderr).strip()


def snapshot(root: Path) -> dict[str, str]:
    """Map every file under ``root`` (except git metadata and caches) to a content hash."""
    files: dict[str, str] = {}
    for directory, names, filenames in os.walk(root):
        here = Path(directory)
        for name in list(names):
            if name in IGNORED_DIRS:
                names.remove(name)
            elif (here / name).is_symlink():
                filenames.append(name)  # a symlinked directory is recorded as a link, never followed
                names.remove(name)
        for filename in sorted(filenames):
            path = here / filename
            relative = path.relative_to(root).as_posix()
            if path.is_symlink():
                files[relative] = "symlink:" + os.readlink(path)
            else:
                files[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    return files


def changed_paths(before: dict[str, str], after: dict[str, str]) -> list[str]:
    return sorted(path for path in before.keys() | after.keys() if before.get(path) != after.get(path))


# --- git and the generated core --------------------------------------------------------------------------------


def _git_env(when: dt.datetime | None = None) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1")
    if when is not None:
        stamp = when.isoformat()
        env.update(
            GIT_AUTHOR_NAME=IDENTITY[0],
            GIT_AUTHOR_EMAIL=IDENTITY[1],
            GIT_COMMITTER_NAME=IDENTITY[0],
            GIT_COMMITTER_EMAIL=IDENTITY[1],
            GIT_AUTHOR_DATE=stamp,
            GIT_COMMITTER_DATE=stamp,
        )
    return env


def git(repo: Path, *args: str, when: dt.datetime | None = None) -> str:
    completed = subprocess.run(
        ["git", *args], cwd=repo, env=_git_env(when), capture_output=True, text=True, check=False
    )
    if completed.returncode != 0:
        raise ScenarioError(f"git {' '.join(args)} failed in {repo}: {completed.stderr.strip()}")
    return completed.stdout.strip()


def assert_outside_git(path: Path) -> Path:
    """Refuse a path inside any git repository; a path that does not exist yet is judged by its parents."""
    resolved = path.resolve()
    for candidate in (resolved, *resolved.parents):
        if (candidate / ".git").exists():
            raise ScenarioError(f"{resolved} is inside the git repository at {candidate}")
    return resolved


def assert_safe_root(root: Path) -> Path:
    """Refuse a scenario root inside ~/Projects or inside any git repository."""
    resolved = assert_outside_git(root)
    projects = (Path.home() / "Projects").resolve()
    if resolved == projects or projects in resolved.parents:
        raise ScenarioError(f"{resolved} is inside {projects}; build scenarios under a temporary directory")
    return resolved


def generate_core(parent: Path, when: dt.datetime) -> dict[str, str]:
    """Run ``init_template.py new`` (core profile) into a fresh directory under ``parent``; return its files."""
    target = Path(tempfile.mkdtemp(prefix="core-", dir=parent))
    try:
        env = clean_env()
        env["SOURCE_DATE_EPOCH"] = str(int(when.timestamp()))
        completed = subprocess.run(
            [
                sys.executable,
                str(INIT_SCRIPT),
                "new",
                "--name",
                "Notes",
                "--target",
                str(target),
                "--profile",
                "core",
                "--no-init-git",
            ],
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        if completed.returncode != 0:
            raise ScenarioError(f"init_template.py new failed: {completed.stdout}{completed.stderr}")
        return {
            path.relative_to(target).as_posix(): path.read_text(encoding="utf-8")
            for path in sorted(target.rglob("*"))
            if path.is_file()
        }
    finally:
        shutil.rmtree(target, ignore_errors=True)


