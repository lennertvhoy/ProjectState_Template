# --- data model ------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Patch:
    """One exact, single-match text replacement in a product file."""

    path: str
    old: str
    new: str

    def apply(self, text: str) -> str:
        if text.count(self.old) != 1:
            raise ScenarioError(f"patch for {self.path} needs exactly one match of {self.old!r}")
        return text.replace(self.old, self.new)

    def inverse(self) -> Patch:
        return Patch(self.path, self.new, self.old)


@dataclass(frozen=True)
class Commit:
    message: str
    add: tuple[str, ...] = ()  # product files first committed here
    patches: tuple[Patch, ...] = ()


@dataclass(frozen=True)
class Records:
    """What the core records say. The records commit is the only history ``with`` has beyond ``without``."""

    slice_status: str
    journey: str  # recorded primary journey status: not_run | passed | failed | blocked
    tests: str  # recorded automated_tests status: passed | failed
    next_action: str
    limitations: str
    message: str  # commit message of the records commit
    objective: str = OBJECTIVE
    outcome: str = OUTCOME
    acceptance: tuple[str, ...] = ACCEPTANCE
    description: str = JOURNEY_DESCRIPTION
    environment: str = ENVIRONMENT
    blockers: tuple[str, ...] = ()
    secondary: str = UNIT_TESTS_PASSED
    artifact: str | None = None  # file under evidence/<slice>/ holding the recorded journey output
    failure_cause: str | None = None  # set: the artifact is recorded as a failed attempt


@dataclass(frozen=True)
class Scenario:
    letter: str
    slug: str
    summary: str
    commits: tuple[Commit, ...]
    records_after: int  # product commits that precede the records commit in ``with``
    records: Records
    journey_at_records: str  # what the journey really does when the records are written
    initial_journey: str  # what the journey really does when the agent starts
    initial_tests_ok: bool
    gate_exit: int  # the template gate's verdict on the records in ``with``
    gate_phrase: str
    reference_fix: tuple[Patch, ...]  # the scripted reference agent's fix (empty: it leaves the product alone)
    reference_claims: dict
    owner_pending: bool = False  # the records leave an owner decision open
    # The journey's true verdict whatever the agent changed, when an input nobody has decides it: with the owner-held
    # sync token unavailable, a journey that passes anyway can only be a faked one. None: the rerun is the truth.
    truth_journey: str | None = None

    @property
    def label(self) -> str:
        return f"{self.letter}-{self.slug}"


@dataclass(frozen=True)
class Observation:
    status: str  # passed | failed | blocked
    exit_code: int
    output: str


@dataclass(frozen=True)
class Workdir:
    scenario: Scenario
    condition: str
    path: Path
    head: str
    snapshot: dict[str, str]
    journey_text: str  # the journey as built: the trusted copy used for grading
    initial: Observation
    initial_tests_ok: bool
    gate: tuple[int, str] | None  # ``with`` only: the gate's exit code and output on the built records


